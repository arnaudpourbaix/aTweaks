import chalk from "chalk";
import figureSet from "figures";
import {
  BaseCreature,
  Creature,
  CreatureAutoGenerate,
} from "../model/creature/creature";
import { CreatureData } from "../model/creature/data";
import { AttackPerRoundTable } from "../model/game-data/attack-per-round";
import { DexterityTable } from "../model/game-data/dexterity";
import { EnchantmentTable } from "../model/game-data/enchantement";
import { SAVING_THROWS } from "../model/game-data/saving-throws";
import { CreatureSizeTable } from "../model/game-data/sizes";
import { StrengthTable } from "../model/game-data/strength";
import { Thac0Table } from "../model/game-data/thac0";
import {
  ItemAbilityLocationEnum,
  ItemFlagEnum,
} from "../model/spell-item/effect.enums";
import { Weapon } from "../model/spell-item/spell-item";
import hitPointService from "./hit-point.service";
import itemService from "./item.service";
import kitService from "./kit.service";

class CreatureService {
  check(creature: Creature) {
    this.checkData({
      creature,
      base: creature,
      isAdjustment: false,
    });
    for (const a of creature.adjustments) {
      this.checkData({
        creature,
        base: a,
        isAdjustment: true,
      });
    }
  }

  checkData(p: {
    creature: Creature;
    base: BaseCreature;
    isAdjustment: boolean;
  }): void {
    const data = p.base.data;
    console.log(p.base.files);
    kitService.applyKit(p.creature, p.isAdjustment ? p.base : undefined);
    if (p.creature.attack?.dualWielding && !p.isAdjustment) {
      if (!data.apr)
        throw new Error(
          "Attacks per round need to be set for dual wielding flag",
        );
      data.apr -= 1;
      console.log(
        `${figureSet.arrowRight} setting dual wield: ${data.apr} APR +1 offhand`,
      );
    }
    if (data.dexterity !== undefined && data.ac !== undefined) {
      const bonus = this.getDexterityArmorClassBonus(data);
      if (bonus) {
        console.log(
          `${figureSet.arrowRight} AC reduced to ${data.ac - bonus} (was ${
            data.ac
          }) because of dexterity bonus (${bonus})`,
        );
        data.ac -= bonus;
      }
    }
    if (!p.isAdjustment && this.hasOffhandWeapon(p.creature)) {
      console.log(`${figureSet.arrowRight} dual wielding detected`);
      p.creature.attack.dualWielding = true;
    }
    this.checkMovement(p);
    this.transformAttackPerRound(p.creature.data);
    this.autogenerateData({
      data,
      autoGenerate: p.creature.autoGenerate,
      creature: p.creature,
      parent: p.isAdjustment ? p.creature.data : undefined,
    });
  }

  hasOffhandWeapon(creature: Creature): boolean {
    const equippedItem = creature.data.items.equipped.find((i) =>
      itemService.isSlotIncluded([i], "SHIELD"),
    );
    const item = creature.items.find((i) => i.file === equippedItem?.file);
    return item?.header?.location === ItemAbilityLocationEnum.Weapon;
  }

  private checkMovement(p: {
    creature: Creature;
    base: BaseCreature;
    isAdjustment: boolean;
  }) {
    const data = p.base.data;
    if (!data.movement && !p.isAdjustment)
      throw new Error("movement not set !");
    const movement = data.movement ?? p.creature.data.movement;
    if (data.kit === "BARBARIAN" && movement) {
      data.movement = movement.clone();
      data.movement.bonus += 2;
      console.log(
        `${figureSet.arrowRight} movement increased to ${data.movement} (barbarian): `,
      );
    }
  }

  private transformAttackPerRound(data?: Partial<CreatureData>) {
    if (!data || !data.apr) return;
    const apr = this.getAttacksPerRound(data.apr);
    data.apr = apr.value;
    if (data.movement) {
      data.movement.hasImprovedHaste = apr.doubleApr;
    }
  }

  getAttacksPerRound(value: number): {
    apr: number;
    value: number;
    doubleApr: boolean;
  } {
    const item = AttackPerRoundTable.find((t) => t.apr === value);
    if (!item) {
      throw new Error(`attack per round not found in table: ${value}`);
    }
    return item;
  }

  autogenerateData(p: {
    autoGenerate: CreatureAutoGenerate;
    data: Partial<CreatureData>;
    creature: Creature;
    parent: CreatureData | undefined;
  }) {
    if (p.autoGenerate.hitPoints && p.data.hp === undefined) {
      this.autogenerateHitPoints({
        data: p.data,
        creature: p.creature,
        parent: p.parent,
      });
    }
    if (p.autoGenerate.thac0 && p.data.thac0 === undefined) {
      this.autogenerateThac0(p.data, p.parent);
    }
    if (p.data.saveBreath === undefined) {
      this.autogenerateSavingThrows({
        data: p.data,
        parent: p.parent,
        options: p.autoGenerate.savingThrows,
      });
    }
  }

  checkWeapons(creature: Creature) {
    for (const item of creature.items) {
      if (item.header?.location === ItemAbilityLocationEnum.Weapon) {
        this.checkWeapon(creature, item as Weapon);
      }
    }
  }

  private checkWeapon(creature: Creature, weapon: Weapon) {
    const level = creature.data.level1.pnpValue;
    if (!weapon.header.speed) {
      weapon.header.speed = 3;
      console.log(
        `${figureSet.warning} default speed of ${weapon.header.speed} from weapon ${weapon.file}.`,
      );
    }
    if (
      level !== undefined &&
      weapon.enchantment === undefined &&
      creature.autoGenerate.enchantment
    ) {
      const item = EnchantmentTable.find(
        (e) =>
          level > e.level ||
          (level == e.level &&
            !!creature.data.bonusHp &&
            creature.data.bonusHp >= e.bonusHp),
      );
      if (!item) {
        throw new Error(
          `enchantment not found in table: ${level}/${creature.data.bonusHp}`,
        );
      }
      if (item.enchant > 0) {
        // console.log(creature.data.class, 'enchant:', enchant.enchant);
        weapon.enchantment = item.enchant;
        if (
          item.enchant &&
          (!weapon.flags || !weapon.flags.includes(ItemFlagEnum.Magical))
        ) {
          weapon.flags = weapon.flags ?? [];
          weapon.flags.push(ItemFlagEnum.Magical);
        }
      }
    }
    if (
      weapon.header.projectile === undefined &&
      weapon.header.range === undefined &&
      creature.autoGenerate.meleeRange
    ) {
      const range = CreatureSizeTable.find(
        (c) => c.size === creature.data.size,
      );
      if (range) {
        console.log(
          `${figureSet.arrowRight} Melee range: ${range.attackRange}`,
        );
        weapon.header.range = range.attackRange;
      }
    }
  }

  private autogenerateHitPoints(p: {
    data: Partial<CreatureData>;
    creature: Creature;
    parent?: CreatureData;
  }) {
    const value = hitPointService.getHitPoints(p);
    if (value) p.data.hp = value;
  }

  private autogenerateThac0(
    data: Partial<CreatureData>,
    parent?: CreatureData,
  ) {
    let level = data.level1?.pnpValue;
    if (!level && !parent)
      throw new Error(`Can't generate thac0 because level1 is unknown`);
    else if (!level) return;
    if (!!data.bonusHp && data.bonusHp >= 3) {
      level++;
      console.log(
        `${figureSet.arrowRight} calculating THAC0 as a level ${level} creature`,
      );
    }
    const item = Thac0Table.find((t) => t.level === level);
    if (!item) {
      throw new Error(`thac0 not found in table for level ${level}`);
    }
    if (data.thac0 !== undefined)
      console.log(
        chalk.yellowBright(
          `${figureSet.warning} level: ${level}, hp bonus: ${data.bonusHp}, thac0: ${data.thac0}, calculated: ${item.thac0}`,
        ),
      );
    else data.thac0 = item.thac0;
  }

  convertMovement(movement: number): number {
    // aVENGER was using a coef of 0.75
    const result = Math.round(movement * 0.8);
    return result;
  }

  getSavingThrows(p: Exclude<CreatureAutoGenerate["savingThrows"], undefined>) {
    let key: keyof typeof SAVING_THROWS = "fighter";
    if (p.classe === "DRUID" || p.classe === "CLERIC") key = "priest";
    else if (p.classe === "MAGE") key = "wizard";
    const table = SAVING_THROWS[key];
    const saves = table.find(
      (t) => p.level >= t.levels[0] && p.level <= t.levels[1],
    ) as {
      saveDeath: number;
      saveWand: number;
      savePolymorph: number;
      saveBreath: number;
      saveSpell: number;
    };
    if (key !== "fighter")
      console.log(
        `${figureSet.arrowRight} Level: ${p.level}, class: ${
          p.classe
        }, saving throws table: ${key}, ${JSON.stringify(saves)}`,
      );
    return {
      saveDeath: saves.saveDeath - (p.bonus?.saveDeath ?? 0),
      saveWand: saves.saveWand - (p.bonus?.saveWand ?? 0),
      savePolymorph: saves.savePolymorph - (p.bonus?.savePolymorph ?? 0),
      saveBreath: saves.saveBreath - (p.bonus?.saveBreath ?? 0),
      saveSpell: saves.saveSpell - (p.bonus?.saveSpell ?? 0),
    };
  }

  private autogenerateSavingThrows({
    data,
    parent,
    options,
  }: {
    data: Partial<CreatureData>;
    parent?: CreatureData;
    options: CreatureAutoGenerate["savingThrows"];
  }) {
    const level = data.level1;
    if (!level && !parent)
      throw new Error(`Can't generate saving throws because level1 is unknown`);
    else if (!level) return;
    const classe = data.class ?? parent?.class;
    const saves = this.getSavingThrows({
      level: options?.level ?? level.pnpValue,
      classe: options?.classe ?? classe,
      bonus: options?.bonus,
    });
    data.saveDeath = saves.saveDeath;
    data.saveWand = saves.saveWand;
    data.savePolymorph = saves.savePolymorph;
    data.saveBreath = saves.saveBreath;
    data.saveSpell = saves.saveSpell;
  }

  getStrengthBonus(data: Partial<CreatureData>): {
    hit: number;
    damage: number;
  } {
    if (data.strength === undefined) return { hit: 0, damage: 0 };
    const exStrength = data.exceptionalStrength ?? 0;
    const item = StrengthTable.find((t) => {
      const checkStr = t.str === data.strength;
      const checkStrEx =
        t.strEx === undefined ||
        (exStrength >= t.strEx[0] && exStrength <= t.strEx[1]);
      return checkStr && checkStrEx;
    });
    if (!item) {
      throw new Error(
        `strength not found in table: ${data.strength}/${exStrength}`,
      );
    }
    return item;
  }

  getDexterityArmorClassBonus(data: Partial<CreatureData>): number {
    if (data.dexterity === undefined) return 0;
    const item = DexterityTable.find((t) => t.dex === data.dexterity);
    if (!item) {
      throw new Error(`dexterity not found in table: ${data.dexterity}`);
    }
    return item.ac;
  }

  getFinalArmorClass(base: BaseCreature) {
    if (base.data.dexterity === undefined || base.data.ac === undefined)
      throw new Error(`can't calculate final AC because of missing data`);
    return base.data.ac + this.getDexterityArmorClassBonus(base.data);
  }
}

const creatureService = new CreatureService();
export default creatureService;
